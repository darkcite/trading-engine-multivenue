//! COPY-DOCTRINE: build script — runs once in cargo's build step and is linked into no binary;
//! every copy here is cold.
//!
//! Deterministic writer of `$OUT_DIR/spec_gen.rs` and `$OUT_DIR/chart_gen.rs` (impl-00 §4.8):
//! a pure function of the model, the MPH and the input hash. Collections are sorted `Vec`s or
//! `BTreeMap`s; every number is an integer literal (an `f64` as its `to_bits` hex); every item
//! has a `///` line; `pine-ir` items are named by full path and the file contains no `use`.

use crate::chart::Chart;
use crate::mph::Mph;
use crate::schema::{DefVal, MSwitch, Model, Sig, VBits};
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// The generated file's first line.
pub const HEADER: &str =
    "// @generated by crates/pine-spec/build.rs from spec/builtins.json — do not edit\n";

/// The `NAMES` blob under construction: exact duplicates share one span.
struct Names {
    blob: String,
    seen: BTreeMap<String, (u32, u32)>,
}

impl Names {
    fn span(&mut self, s: &str) -> (u32, u32) {
        if s.is_empty() {
            return (0, 0);
        }
        if let Some(&sp) = self.seen.get(s) {
            return sp;
        }
        let sp = (self.blob.len() as u32, s.len() as u32);
        // COPY: build time — the blob is the emitted `NAMES` literal.
        self.blob.push_str(s);
        self.seen.insert(s.to_string(), sp);
        sp
    }
}

fn ss(sp: (u32, u32)) -> String {
    if sp == (0, 0) {
        "SpecStr::EMPTY".to_string()
    } else {
        format!("SpecStr {{ off: {}, len: {} }}", sp.0, sp.1)
    }
}

fn packed(sp: (u32, u32)) -> u64 {
    sp.0 as u64 | (sp.1 as u64) << 32
}

fn sig(s: &Sig) -> String {
    format!(
        "SigTy {{ ty: pine_ir::TypeQ {{ ty: pine_ir::Ty::{:?}, qual: pine_ir::Qual::{:?}, a: {}, \
         b: {}, _pad: 0 }}, tv: {}, _pad: 0 }}",
        s.ty.ty, s.ty.qual, s.ty.a, s.ty.b, s.tv
    )
}

/// One line of doc text: newlines folded to spaces.
fn doc(s: &str) -> String {
    s.replace(['\n', '\r'], " ")
}

/// `int_div` → `IntDiv`.
pub fn camel(id: &str) -> String {
    let mut out = String::with_capacity(id.len());
    for part in id.split('_') {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            // COPY: build time — the rest of the id's part into the generated identifier.
            out.extend(cs);
        }
    }
    out
}

/// A switch default's reading code (validated by R15 before emission).
fn code(s: &MSwitch, d: &str) -> u8 {
    s.readings.iter().position(|r| r == d).unwrap_or(0) as u8
}

/// Emit `spec_gen.rs`.
pub fn spec(m: &Model, mph: &Mph, sha: &[u8; 32]) -> String {
    let mut nm = Names {
        blob: String::new(),
        seen: BTreeMap::new(),
    };

    // NAMES in the fixed traversal of §4.8.
    let ns_sp: Vec<(u32, u32)> = m.namespaces.iter().map(|s| nm.span(s)).collect();
    let mut ent = String::new();
    let mut ovs = String::new();
    let mut prm = String::new();
    let mut ovmod = String::new();
    let mut val_sp: Vec<Option<(u32, u32)>> = vec![None; m.values.len()];
    for e in &m.entries {
        let full = nm.span(&e.full);
        let ns = nm.span(&e.ns);
        let name = nm.span(&e.name);
        let decline = nm.span(&e.decline);
        let _ = writeln!(
            ent,
            "    Entry {{ full: {}, ns: {}, name: {}, decline: {}, ov_lo: {}, ov_hi: {}, \
             val_lo: {}, val_hi: {}, tier: Tier::T{}, scope: Scope::{}, versions: \
             VersionMask({}), is_type: {} }},",
            ss(full),
            ss(ns),
            ss(name),
            ss(decline),
            e.ov_lo,
            e.ov_hi,
            e.val_lo,
            e.val_hi,
            e.tier,
            if e.declined { "Declined" } else { "In" },
            e.versions,
            e.is_type
        );
        for oi in e.ov_lo as usize..e.ov_hi as usize {
            let o = &m.overloads[oi];
            let sym = nm.span(&o.sym);
            for p in &m.params[o.p_lo as usize..o.p_hi as usize] {
                let pn = nm.span(&p.name);
                let (kind, bits) = match &p.default {
                    DefVal::None => ("None", 0u64),
                    DefVal::Int(i) => ("Int", *i as u64),
                    DefVal::Float(f) => ("Float", f.to_bits()),
                    DefVal::Bool(b) => ("Bool", *b as u64),
                    DefVal::Color(c) => ("Color", *c as u64),
                    DefVal::Str(s) => ("Str", packed(nm.span(s))),
                    DefVal::Value(v) => ("Value", *v as u64),
                    DefVal::Na => ("Na", 0),
                };
                let _ = writeln!(
                    prm,
                    "    Param {{ default: DefaultVal {{ bits: {bits:#018x}, kind: \
                     DefaultKind::{kind}, _pad: [0; 7] }}, name: {}, sig: {}, flags: {}, \
                     versions: VersionMask({}), _pad: [0; 4] }},",
                    ss(pn),
                    sig(&p.sig),
                    p.flags,
                    p.versions
                );
            }
            let st = &o.state;
            let w = &o.warmup;
            let opt = |x: Option<&str>, ty: &str| match x {
                Some(v) => format!("Some(pine_ir::{ty}::{v})"),
                None => "None".to_string(),
            };
            let _ = writeln!(
                ovs,
                "    Overload {{ id: pine_ir::OverloadId({oi}), entry: {}, p_lo: {}, p_hi: {}, \
                 r_lo: {}, n_out: {}, bf: {}, state_bytes_min: {}, state: StateSpec {{ shape: \
                 StateShape::{}, param: {}, elem_bytes: {}, hdr_bytes: {}, plus: {}, param2: {}, \
                 _pad: 0 }}, warmup: Warmup {{ kind: WarmKind::{}, param: {}, param2: {}, _pad: \
                 0, bars: {} }}, sym: {}, tv_kinds: [{}, {}, {}], versions: VersionMask({}), \
                 ret_qual: RetQual::{}, abi: Abi::{}, na: NaPolicy::{}, sx: {}, plot: {}, input: \
                 {}, _pad: [0, 0] }},",
                o.entry,
                o.p_lo,
                o.p_hi,
                o.r_lo,
                o.n_out,
                o.bf,
                st.block_bytes0(),
                st.shape,
                st.param,
                st.elem,
                st.hdr,
                st.plus,
                st.param2,
                w.kind,
                w.param,
                w.param2,
                w.bars,
                ss(sym),
                o.tv_kinds[0],
                o.tv_kinds[1],
                o.tv_kinds[2],
                o.versions,
                o.ret_qual,
                o.abi,
                o.na,
                o.sx,
                opt(o.plot, "PlotKind"),
                opt(o.input, "InputKind")
            );
            let _ = writeln!(
                ovmod,
                "    /// `{}` — {}\n    pub const {}: pine_ir::OverloadId = \
                 pine_ir::OverloadId({oi});",
                e.full,
                doc(&e.doc),
                o.sym
            );
        }
        let (lo, hi) = (e.val_lo as usize, e.val_hi as usize);
        for (v, sp) in m.values[lo..hi].iter().zip(val_sp[lo..hi].iter_mut()) {
            if let VBits::Str(s) = &v.bits {
                *sp = Some(nm.span(s));
            }
        }
    }
    let mut vals = String::new();
    for (vi, v) in m.values.iter().enumerate() {
        let bits = match (&v.bits, val_sp[vi]) {
            (VBits::Bits(b), _) => *b,
            (VBits::Str(_), Some(sp)) => packed(sp),
            (VBits::Str(_), None) => 0,
        };
        let _ = writeln!(
            vals,
            "    Value {{ bits: {bits:#018x}, ty: pine_ir::TypeQ {{ ty: pine_ir::Ty::{:?}, qual: \
             pine_ir::Qual::{:?}, a: {}, b: {}, _pad: 0 }}, entry: {}, src: ValueSrc::{}, \
             versions: VersionMask({}), _pad: [0; 4] }},",
            v.ty.ty, v.ty.qual, v.ty.a, v.ty.b, v.entry, v.src, v.versions
        );
    }
    let mut rets = String::new();
    for r in &m.rets {
        let _ = writeln!(rets, "    {},", sig(r));
    }

    let mut sws = String::new();
    let mut swenum = String::new();
    let mut swr = String::new();
    for (i, s) in m.switches.iter().enumerate() {
        let id = nm.span(&s.id);
        let row = nm.span(&s.row);
        let readings = nm.span(&s.readings.join("|"));
        let owner = nm.span(&s.owner);
        let pin = nm.span(&s.pin);
        let source = nm.span(&s.source);
        let is_sw = s.mech == "Switch";
        let (v5, v6) = if is_sw {
            (code(s, &s.v5), code(s, &s.v6))
        } else {
            (0, 0)
        };
        let _ = writeln!(
            sws,
            "    Switch {{ id: {}, row: {}, readings: {}, owner: {}, pin: {}, source: {}, v5: \
             {v5}, v6: {v6}, mech: SwMech::{}, normative: {} }},",
            ss(id),
            ss(row),
            ss(readings),
            ss(owner),
            ss(pin),
            ss(source),
            s.mech,
            s.normative
        );
        if is_sw {
            let _ = writeln!(
                swenum,
                "    /// {} `{}`: {}\n    {} = {i},",
                s.row,
                s.id,
                doc(&s.doc),
                camel(&s.id)
            );
            for (c, r) in s.readings.iter().enumerate() {
                let _ = writeln!(
                    swr,
                    "    /// `{}` reading `{r}`.\n    pub const {}_{}: u8 = {c};",
                    s.id,
                    s.id.to_ascii_uppercase(),
                    r.to_ascii_uppercase()
                );
            }
        }
    }
    let mut dls = String::new();
    for d in &m.deltas {
        let id = nm.span(&d.id);
        let what = nm.span(&d.what);
        let subj: Vec<&str> = d.subjects.iter().map(|s| s.1.as_str()).collect();
        let subjects = nm.span(&subj.join("|"));
        let source = nm.span(&d.source);
        let pin = nm.span(&d.pin);
        let sw = if d.mech == "Switch" {
            m.switches
                .iter()
                .position(|s| s.id == d.switch)
                .unwrap_or(255)
        } else {
            255
        };
        let _ = writeln!(
            dls,
            "    Delta {{ id: {}, what: {}, subjects: {}, source: {}, pin: {}, mech: \
             DeltaMech::{}, switch: {sw}, _pad: [0, 0] }},",
            ss(id),
            ss(what),
            ss(subjects),
            ss(source),
            ss(pin),
            d.mech
        );
    }
    let mut nsl = String::new();
    for sp in &ns_sp {
        let _ = writeln!(nsl, "    {},", ss(*sp));
    }

    let mut g = String::from(HEADER);
    let _ = writeln!(
        g,
        "/// `builtins.json` `\"schema\"`.\npub const SPEC_SCHEMA: u32 = {};",
        m.schema
    );
    let _ = writeln!(
        g,
        "/// `\"captured_utc\"`: when the references were read.\npub const SPEC_CAPTURED_UTC: \
         &str = {:?};",
        m.captured_utc
    );
    let _ = writeln!(
        g,
        "/// SHA-256 of `spec/builtins.json` as read.\npub const SPEC_SHA256: [u8; 32] = {sha:?};"
    );
    let _ = writeln!(
        g,
        "/// One ASCII blob; every `SpecStr` indexes it.\npub static NAMES: &str = {:?};",
        nm.blob
    );
    let counts = [
        ("ENTRY_COUNT", "Entries", m.entries.len()),
        (
            "OVERLOAD_COUNT",
            "Overloads (`== pine_std::BUILTINS.entries.len()`)",
            m.overloads.len(),
        ),
        ("PARAM_COUNT", "Parameter rows", m.params.len()),
        ("RET_COUNT", "Result rows", m.rets.len()),
        ("VALUE_COUNT", "Value rows", m.values.len()),
        ("NS_COUNT", "Namespaces", m.namespaces.len()),
        ("SWITCH_COUNT", "Switch rows", m.switches.len()),
        ("DELTA_COUNT", "Delta rows", m.deltas.len()),
    ];
    for (n, d, v) in counts {
        let _ = writeln!(g, "/// {d}.\npub const {n}: usize = {v};");
    }
    let tables = [
        (
            "ENTRIES",
            "Entry",
            "ENTRY_COUNT",
            "Entries, ascending by `full` (bytewise).",
            &ent,
        ),
        (
            "OVERLOADS",
            "Overload",
            "OVERLOAD_COUNT",
            "Overloads: `OVERLOADS[i].id == OverloadId(i)`.",
            &ovs,
        ),
        (
            "PARAMS",
            "Param",
            "PARAM_COUNT",
            "Parameter rows per overload, declaration order.",
            &prm,
        ),
        (
            "RETS",
            "SigTy",
            "RET_COUNT",
            "Result rows per overload (`n_out` each).",
            &rets,
        ),
        (
            "VALUES",
            "Value",
            "VALUE_COUNT",
            "Value rows per entry, file order.",
            &vals,
        ),
        (
            "NAMESPACES",
            "SpecStr",
            "NS_COUNT",
            "Namespaces, ascending.",
            &nsl,
        ),
        (
            "SWITCHES",
            "Switch",
            "SWITCH_COUNT",
            "The semantics switch table (§3.11 row order).",
            &sws,
        ),
        (
            "DELTAS",
            "Delta",
            "DELTA_COUNT",
            "The dialect delta table (§3.10 row order).",
            &dls,
        ),
    ];
    for (n, t, c, d, body) in tables {
        let _ = writeln!(g, "/// {d}\npub static {n}: [{t}; {c}] = [\n{body}];");
    }
    let _ = writeln!(
        g,
        "/// One variant per `SWITCHES` row whose `mech` is `Switch`; discriminant = that row's \
         index.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n#[repr(u8)]\npub enum Sw \
         {{\n{swenum}}}"
    );
    let _ = writeln!(
        g,
        "/// Reading codes: `<ID>_<READING>` upper-cased; code = the reading's position in the \
         row.\npub mod swr {{\n{swr}}}"
    );
    let _ = writeln!(
        g,
        "/// Every overload's id by its stable symbol.\npub mod ov {{\n{ovmod}}}"
    );
    let _ = writeln!(
        g,
        "/// The MPH seed.\nconst MPH_SEED: u64 = {:#018x};",
        mph.seed
    );
    let _ = writeln!(
        g,
        "/// The MPH bucket count.\nconst MPH_BUCKETS: u32 = {};",
        mph.buckets
    );
    let _ = writeln!(
        g,
        "/// The MPH displacement per bucket.\nstatic MPH_DISP: [u32; {}] = {:?};",
        mph.disp.len(),
        mph.disp
    );
    let _ = writeln!(
        g,
        "/// The MPH slots: entry index, or `u16::MAX` = empty.\nstatic MPH_SLOTS: [u16; {}] = {:?};",
        mph.slots.len(),
        mph.slots
    );
    g
}

/// Emit `chart_gen.rs` (the §3.12 constants in that order).
pub fn chart(c: &Chart, sha: &[u8; 32]) -> String {
    let mut g = String::from(
        "// @generated by crates/pine-spec/build.rs from tests/conformance/chart.json — do not \
         edit\n",
    );
    let _ = writeln!(
        g,
        "/// `chart.json` schema.\npub const SCHEMA: u32 = {};",
        c.schema
    );
    let _ = writeln!(
        g,
        "/// The freeze day (CH7's input), not a capture stamp.\npub const FROZEN_UTC: &str = \
         {:?};",
        c.frozen_utc
    );
    let _ = writeln!(
        g,
        "/// TradingView's spelling of the symbol.\npub const SYMBOL: &str = {:?};",
        c.tv_symbol
    );
    let _ = writeln!(
        g,
        "/// Canonical symbol key (00-INDEX §3.1).\npub const SYMBOL_KEY: &str = {:?};",
        c.symbol_key
    );
    let _ = writeln!(
        g,
        "/// `candles.db` `descriptor`.\npub const CANDLES_DESCRIPTOR: &str = {:?};",
        c.candles_descriptor
    );
    let _ = writeln!(
        g,
        "/// TradingView timeframe string.\npub const TIMEFRAME_TV: &str = {:?};",
        c.timeframe_tv
    );
    let _ = writeln!(
        g,
        "/// Bar length in seconds.\npub const TIMEFRAME_S: u32 = {};",
        c.timeframe_s
    );
    let _ = writeln!(
        g,
        "/// Chart timezone.\npub const TIMEZONE: &str = {:?};",
        c.timezone
    );
    let _ = writeln!(
        g,
        "/// Chart type.\npub const CHART_TYPE: &str = {:?};",
        c.chart_type
    );
    let _ = writeln!(
        g,
        "/// Bar magnifier (refused).\npub const BAR_MAGNIFIER: bool = {};",
        c.bar_magnifier
    );
    let _ = writeln!(
        g,
        "/// Open of the first judged bar, UTC ms.\npub const FROM_MS: i64 = {};",
        c.from_ms
    );
    let _ = writeln!(
        g,
        "/// Judged window, bars.\npub const BARS: u32 = {};",
        c.bars
    );
    let _ = writeln!(
        g,
        "/// Bars replayed before `FROM_MS`.\npub const WARMUP_BARS: u32 = {};",
        c.warmup_bars
    );
    let _ = writeln!(
        g,
        "/// SHA-256 of `tests/conformance/chart.json` as read.\npub const SHA256: [u8; 32] = \
         {sha:?};"
    );
    g
}
