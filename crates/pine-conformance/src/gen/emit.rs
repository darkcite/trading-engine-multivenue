//! Pine emission (impl-06 §4.2.0): SPDX pair, version line, `indicator`, the header comment, the
//! prelude, the body, the plots. GENERATOR-TIME ONLY: allocates freely.
//!
//! Indentation comes only from [`INDENT`] (I5, `gen_indents_through_one_constant`).

use crate::fixture::{Dialects, FixtureId};
use crate::syn;

/// Spaces per block level: `pine_lang::INDENT_UNIT_SPACES` (impl-01 v4 §3.11: "the generator's only
/// source of indentation"; T15 added the `pine-lang` edge).
pub const INDENT: usize = pine_lang::INDENT_UNIT_SPACES as usize;

/// The `display =` argument of every fixture plot (§4.2.0; flips to `display.all` if probe-00 shows
/// data-window plots are not exported, R11).
pub const PLOT_DISPLAY: &str = "display.data_window";

/// The SPDX pair, lines 1–2 of every generated `.pine` (§4.10 reads `head -3`).
pub const SPDX_PAIR: &str =
    "// SPDX-License-Identifier: Apache-2.0\n// Copyright 2026 Anton (darkcite)\n";

/// What precedes the body.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Prelude {
    /// SYN-1 (§4.1.1).
    Syn1,
    /// SYN-T with the chart window's `FROM_MS` / `STOP_MS` (§4.1.3).
    SynT {
        /// `pine_spec::chart::FROM_MS`.
        from_ms: i64,
        /// `TO_MS − 2·TF_MS`.
        stop_ms: i64,
    },
    /// No prelude.
    None,
}

/// One body line at a block depth.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Line {
    /// Block depth (0 = top level).
    pub depth: u8,
    /// The text, without indentation.
    pub text: String,
}

impl Line {
    /// A top-level line.
    pub fn top(text: impl Into<String>) -> Self {
        Self {
            depth: 0,
            text: text.into(),
        }
    }

    /// A line one block deep.
    pub fn block(text: impl Into<String>) -> Self {
        Self {
            depth: 1,
            text: text.into(),
        }
    }
}

/// One generated script.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Script {
    /// Its fixture id.
    pub id: FixtureId,
    /// Declared dialects; a `56` script is stored as v6 (§4.3).
    pub dialects: Dialects,
    /// Header comment fields between the id and `dialects` (title, axes).
    pub about: Vec<String>,
    /// The other-dialect twin (§4.3), named in the header comment.
    pub twin: Option<FixtureId>,
    /// Pins named in the header comment.
    pub pins: Vec<String>,
    /// The declaration line when it is not the default `indicator("<ID>", overlay = false)` (F096's
    /// arguments, F097's `strategy("F097")`).
    pub decl: Option<String>,
    /// The prelude.
    pub prelude: Prelude,
    /// The body.
    pub body: Vec<Line>,
    /// `(expression, suffix)`: emitted as `plot(<expr>, "f_<ID>_<suffix>", display = …)`.
    pub plots: Vec<(String, String)>,
}

/// `INDENT · depth` spaces.
pub fn indent(depth: u8) -> String {
    " ".repeat(INDENT * usize::from(depth))
}

/// A wrapped line's indentation, `INDENT + 1` spaces: Pine reads a line indented by a non-multiple
/// of the block unit as a continuation (§4.2.5's baseline `strategy(…)` header wraps with five).
pub fn continuation() -> String {
    " ".repeat(INDENT + 1)
}

/// The version line a stored script carries (§4.2.0: a `dialects 56` fixture is stored as v6).
pub fn version_line(ds: Dialects) -> &'static str {
    if ds == Dialects::V5 {
        "//@version=5"
    } else {
        "//@version=6"
    }
}

/// `x_<ID>`: every identifier a fixture declares ends in `_<ID>` (§4.2.0).
pub fn sfx(name: &str, id: FixtureId) -> String {
    format!("{name}_{}", id.as_str())
}

/// The plot title `f_<ID>_<suffix>` (I4).
pub fn plot_title(id: FixtureId, suffix: &str) -> String {
    format!("f_{}_{suffix}", id.as_str())
}

/// The `.pine` bytes.
///
/// `pin:06-header-comment` — the comment line is
/// `// <ID> · <about…> · dialects <ds>[ · twin <ID>][ · <pin>…] · generated by pine-conf gen; do
/// not edit`, placed after `indicator(…)`. `pin:06-template-governs-examples` (lead ruling,
/// 2026-10-17): §4.2.0's template governs; §4.2.1's A074/A090 examples are amended to this form
/// (`AMEND-06-a074-a090.md`).
pub fn render(s: &Script) -> String {
    let id = s.id.as_str();
    let mut o = String::with_capacity(1024);
    o.push_str(SPDX_PAIR);
    o.push_str(version_line(s.dialects));
    o.push('\n');
    match &s.decl {
        Some(d) => {
            o.push_str(d);
            o.push('\n');
        }
        None => o.push_str(&format!("indicator(\"{id}\", overlay = false)\n")),
    }
    let mut c = vec![id.to_string()];
    c.extend(s.about.iter().cloned());
    c.push(format!("dialects {}", s.dialects.text()));
    if let Some(t) = s.twin {
        c.push(format!("twin {}", t.as_str()));
    }
    c.extend(s.pins.iter().cloned());
    c.push("generated by pine-conf gen; do not edit".to_string());
    o.push_str(&format!("// {}\n", c.join(" · ")));
    match s.prelude {
        Prelude::Syn1 => o.push_str(syn::SYN1_PRELUDE),
        Prelude::SynT { from_ms, stop_ms } => o.push_str(&syn::syn_t_prelude(from_ms, stop_ms)),
        Prelude::None => {}
    }
    o.push_str(&render_body(s));
    o
}

/// The body lines and the plots — what a sheet concatenates (§4.7.5).
pub fn render_body(s: &Script) -> String {
    let mut o = String::with_capacity(512);
    for l in &s.body {
        o.push_str(&indent(l.depth));
        o.push_str(&l.text);
        o.push('\n');
    }
    for (expr, suffix) in &s.plots {
        o.push_str(&format!(
            "plot({expr}, \"{}\", display = {PLOT_DISPLAY})\n",
            plot_title(s.id, suffix)
        ));
    }
    o
}

/// The isna/val pair (§4.2.0): `na(E) ? 1 : 0` and `na(E) ? na : PROJ(E)`.
pub fn isna_val(e: &str, proj: &str) -> Vec<(String, String)> {
    vec![
        (format!("na({e}) ? 1 : 0"), "isna".to_string()),
        (format!("na({e}) ? na : {proj}"), "val".to_string()),
    ]
}
