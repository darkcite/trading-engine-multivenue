//! Sheet packing for capture (impl-06 §4.7.5): one indicator = one prelude plus the concatenated
//! bodies of up to [`MAX_FIXTURES`] fixtures (≤ [`MAX_PLOTS`] plots, ≤ [`MAX_REQ_FIXTURES`]
//! request-bearing fixtures, ≤ [`MAX_REQUESTS`] requests), same dialect, alignment and prelude, every
//! one a `series` expectation with no `refuse` / `fault` reading. GENERATOR-TIME ONLY.
//!
//! `pin:06-sheet-dialect-split` — §4.3 says `sheets/v5/` and `sheets/v6/` "differ only in the version
//! line"; that holds for `dialects 56` fixtures only. They pack into `sheet-<G>-<NN>` (both dirs, the
//! version line the one difference); a `dialects 5` / `6` fixture packs into `sheet-<G>-v<d>-<NN>` in
//! its own dialect's dir only.
//!
//! `pin:06-sheet-captured-only` — only `tv` fixtures are packed: `algebraic` / `authored` /
//! `declined` need no capture, and `tv_only` pin evidence (D060, E106, E110) is pasted alone
//! (§4.7.2 re-pastes D060 at every session).
//!
//! `pin:06-sheet-no-rt` — a `driver rt` fixture is captured by the realtime method (§4.7.8), never
//! packed.
//!
//! `pin:06-sheet-request-count` — a fixture's requests are the `request.` tokens of its body and
//! plots; it is request-bearing when that count is ≥ 1.

use std::path::Path;

use pine_ir::Dialect;

use super::emit::{self, Prelude, SPDX_PAIR};
use super::Cell;
use crate::fixture::{Dialects, Driver, Expect, FixtureId, Group, Oracle, ReadingBody};

/// Fixtures per sheet (§4.7.5).
pub const MAX_FIXTURES: usize = 8;
/// Plots per sheet (probe-02, R7; halved if it fails).
pub const MAX_PLOTS: usize = 48;
/// Request-bearing fixtures per sheet.
pub const MAX_REQ_FIXTURES: usize = 4;
/// `request.*` calls per sheet (probe-02, R7).
pub const MAX_REQUESTS: usize = 40;

/// Never packed by name (§4.7.5): F079 (a builtin's name), the declaration probes F096/F097, the pin
/// fixtures that may refuse or fault, D057; D060 (`pin:06-sheet-captured-only`, pasted alone).
pub const NEVER_PACKED: [&str; 14] = [
    "D057", "D060", "F079", "F083", "F084", "F085", "F086", "F087", "F088", "F089", "F093", "F095",
    "F096", "F097",
];

/// `tests/conformance/sheets/v<d>`.
pub fn sheet_dir(d: Dialect) -> String {
    format!("{}/sheets/v{}", crate::FIXTURE_ROOT, d as u8)
}

/// One generated sheet.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Sheet {
    /// `sheet-<G>-<NN>` or `sheet-<G>-v<d>-<NN>`.
    pub name: String,
    /// The dialect it is pasted in.
    pub dialect: Dialect,
    /// Its fixtures, in id order.
    pub ids: Vec<FixtureId>,
    /// Plots it carries.
    pub plots: usize,
    /// The `.pine` bytes.
    pub text: String,
}

impl Sheet {
    /// Workspace-relative path.
    pub fn path(&self) -> String {
        format!("{}/{}.pine", sheet_dir(self.dialect), self.name)
    }
}

/// Whether `c` may be packed (§4.7.5).
pub fn packable(c: &Cell) -> bool {
    let id = c.script.id;
    c.oracle == Oracle::Tv
        && c.script.decl.is_none()
        && id.group() != Group::Z
        && !NEVER_PACKED.contains(&id.as_str())
        && c.run.driver != Driver::Rt
        && matches!(c.script.prelude, Prelude::Syn1 | Prelude::None)
        && matches!(c.expect, Expect::Pending | Expect::Series(_))
        && c.readings
            .iter()
            .all(|r| !matches!(r.body, ReadingBody::Refuse(_) | ReadingBody::Fault { .. }))
}

/// `request.` tokens of the body and the plots (`pin:06-sheet-request-count`).
pub fn requests(c: &Cell) -> usize {
    let body: usize = c
        .script
        .body
        .iter()
        .map(|l| l.text.matches("request.").count())
        .sum();
    let plots: usize = c
        .script
        .plots
        .iter()
        .map(|(e, _)| e.matches("request.").count())
        .sum();
    body + plots
}

/// An open bin while packing.
struct Bin {
    group: Group,
    shared: bool,
    key: (u8, u8, u8),
    cells: Vec<usize>,
    plots: usize,
    req_fixtures: usize,
    requests: usize,
}

impl Bin {
    fn fits(&self, plots: usize, req: usize) -> bool {
        self.cells.len() < MAX_FIXTURES
            && self.plots + plots <= MAX_PLOTS
            && self.req_fixtures + usize::from(req > 0) <= MAX_REQ_FIXTURES
            && self.requests + req <= MAX_REQUESTS
    }
}

fn render(name: &str, d: Dialect, cells: &[&Cell]) -> String {
    let mut o = String::with_capacity(4096);
    o.push_str(SPDX_PAIR);
    o.push_str(emit::version_line(match d {
        Dialect::V5 => Dialects::V5,
        Dialect::V6 => Dialects::V6,
    }));
    o.push('\n');
    o.push_str(&format!("indicator(\"{name}\", overlay = false)\n"));
    let ids: Vec<&str> = cells.iter().map(|c| c.script.id.as_str()).collect();
    o.push_str(&format!(
        "// {name} · v{} · {} · generated by pine-conf sheets; do not edit\n",
        d as u8,
        ids.join(" ")
    ));
    if let Some(c) = cells.first() {
        match c.script.prelude {
            Prelude::Syn1 => o.push_str(crate::syn::SYN1_PRELUDE),
            Prelude::SynT { .. } | Prelude::None => {}
        }
    }
    for c in cells {
        o.push_str(&emit::render_body(&c.script));
    }
    o
}

/// Every sheet of dialect `d`, packed next-fit in id order per (group, sharing, driver, alignment,
/// prelude); named in order of their first fixture.
pub fn sheets(d: Dialect) -> Vec<Sheet> {
    let mut cells = super::cells();
    cells.sort_by_key(|c| c.script.id);
    let mut open: Vec<Bin> = Vec::new();
    let mut done: Vec<Bin> = Vec::new();
    for (i, c) in cells.iter().enumerate() {
        if !packable(c) || !c.script.dialects.has(d) {
            continue;
        }
        let shared = c.script.dialects == Dialects::BOTH;
        let key = (
            c.run.driver as u8,
            c.run.align as u8,
            u8::from(c.script.prelude == Prelude::Syn1),
        );
        let group = c.script.id.group();
        let (plots, req) = (c.script.plots.len(), requests(c));
        let slot = open
            .iter()
            .position(|b| b.group == group && b.shared == shared && b.key == key);
        if let Some(k) = slot {
            if !open[k].fits(plots, req) {
                done.push(open.remove(k));
            }
        }
        let k = match open
            .iter()
            .position(|b| b.group == group && b.shared == shared && b.key == key)
        {
            Some(k) => k,
            None => {
                open.push(Bin {
                    group,
                    shared,
                    key,
                    cells: Vec::new(),
                    plots: 0,
                    req_fixtures: 0,
                    requests: 0,
                });
                open.len() - 1
            }
        };
        let b = &mut open[k];
        b.cells.push(i);
        b.plots += plots;
        b.req_fixtures += usize::from(req > 0);
        b.requests += req;
    }
    done.append(&mut open);
    done.sort_by_key(|b| cells[b.cells[0]].script.id);
    let mut out = Vec::with_capacity(done.len());
    let mut counters: Vec<(Group, bool, u32)> = Vec::new();
    for b in &done {
        let n = match counters
            .iter_mut()
            .find(|(g, s, _)| *g == b.group && *s == b.shared)
        {
            Some(e) => {
                e.2 += 1;
                e.2
            }
            None => {
                counters.push((b.group, b.shared, 1));
                1
            }
        };
        let letter = b.group.letter();
        let name = if b.shared {
            format!("sheet-{letter}-{n:02}")
        } else {
            format!("sheet-{letter}-v{}-{n:02}", d as u8)
        };
        let members: Vec<&Cell> = b.cells.iter().map(|&i| &cells[i]).collect();
        out.push(Sheet {
            text: render(&name, d, &members),
            ids: members.iter().map(|c| c.script.id).collect(),
            plots: b.plots,
            dialect: d,
            name,
        });
    }
    out
}

/// `pine-conf sheets --dialect d`: writes every sheet of `d` and removes a stale `sheet-*.pine` in
/// that directory. Returns the sheets written.
pub fn write(root: &Path, d: Dialect) -> std::io::Result<Vec<Sheet>> {
    let all = sheets(d);
    let dir = root.join(sheet_dir(d));
    std::fs::create_dir_all(&dir)?;
    for e in std::fs::read_dir(&dir)? {
        let p = e?.path();
        let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
        let stale = name.starts_with("sheet-")
            && name.ends_with(".pine")
            && !all.iter().any(|s| format!("{}.pine", s.name) == name);
        if stale {
            std::fs::remove_file(&p)?;
        }
    }
    for s in &all {
        std::fs::write(root.join(s.path()), &s.text)?;
    }
    Ok(all)
}

/// I7 over the sheets of both dialects: one line per difference (a missing, differing or stale file).
pub fn check(root: &Path) -> Vec<String> {
    let mut diffs = Vec::new();
    for d in [Dialect::V5, Dialect::V6] {
        let all = sheets(d);
        for s in &all {
            match std::fs::read(root.join(s.path())) {
                Ok(b) if b == s.text.as_bytes() => {}
                Ok(_) => diffs.push(format!("{}: differs from the generator", s.path())),
                Err(e) => diffs.push(format!("{}: {e}", s.path())),
            }
        }
        if let Ok(rd) = std::fs::read_dir(root.join(sheet_dir(d))) {
            for e in rd.flatten() {
                let name = e.file_name().to_string_lossy().into_owned();
                if name.ends_with(".pine")
                    && !all.iter().any(|s| format!("{}.pine", s.name) == name)
                {
                    diffs.push(format!("{}/{name}: stale sheet", sheet_dir(d)));
                }
            }
        }
    }
    diffs
}
