/// Bitwise row equality, `na` (NaN) matching only `na`.
fn same(got: &[f64], want: &[f64]) {
    assert_eq!(got.len(), want.len());
    for (i, (g, w)) in got.iter().zip(want).enumerate() {
        let ok = (g.is_nan() && w.is_nan()) || g.to_bits() == w.to_bits();
        assert!(ok, "row {i}: got {g:?}, want {w:?}");
    }
}

const NA: f64 = f64::NAN;

#[test]
fn readings_twins_match_hand_values() {
    let x = [1.0, 2.0, 3.0, 4.0];
    same(&sma(&x, 2), &[NA, 1.5, 2.5, 3.5]);
    same(&sma(&[1.0, NA, 3.0, 4.0], 2), &[NA, NA, NA, 3.5]);
    // ema(3): alpha = 0.5. First seed: 1, then 0.5·2 + 0.5·1 = 1.5, then 2.25, 3.125.
    same(&ema(&x, 3, EmaSeed::First), &[1.0, 1.5, 2.25, 3.125]);
    // SMA seed: na, na, sma(1,2,3) = 2, then 0.5·4 + 0.5·2 = 3.
    same(&ema(&x, 3, EmaSeed::Sma), &[NA, NA, 2.0, 3.0]);
    // rma(2): alpha 0.5, seed sma(1,2) = 1.5, then 2.25, 3.125.
    same(&rma(&x, 2), &[NA, 1.5, 2.25, 3.125]);
    // wma(3) at 3: (3·9 + 2·6 + 1·3) / 18 = 42/18.
    same(&wma(&[1.0, 2.0, 3.0], 3), &[NA, NA, 42.0 / 18.0]);
    // The textbook population deviation: 2.
    let s = stdev(&[2.0, 4.0, 4.0, 4.0, 5.0, 5.0, 7.0, 9.0], 8);
    assert_eq!(s[7], 2.0);
    same(&highest(&[1.0, 3.0, 2.0], 2), &[NA, 3.0, 3.0]);
    same(&change(&[1.0, 4.0, 9.0], 1), &[NA, 3.0, 5.0]);
    same(&rising(&[1.0, 2.0, 3.0, 2.0], 2), &[NA, NA, 1.0, 0.0]);
    same(&falling(&[3.0, 2.0, 1.0, 2.0], 2), &[NA, NA, 1.0, 0.0]);
    same(
        &barssince(&[false, true, false, false, true]),
        &[NA, 0.0, 1.0, 2.0, 0.0],
    );
    // rsi(2) over 1,2,3,2: u = na,1,1,0; d = na,0,0,1; rma(u) = na,na,1,0.5; rma(d) = na,na,0,0.5.
    same(
        &rsi(&x[..3].iter().copied().chain([2.0]).collect::<Vec<_>>(), 2),
        &[NA, NA, 100.0, 50.0],
    );
    // macd(1, 2, 1) with the first seed: fast = x; slow ema(2) alpha 2/3.
    let (m, g, h) = macd(&[3.0, 6.0], 1, 2, 1, EmaSeed::First);
    same(
        &m,
        &[0.0, 6.0 - (2.0 / 3.0 * 6.0 + (1.0 - 2.0 / 3.0) * 3.0)],
    );
    same(&g, &m);
    same(&h, &[0.0, 0.0]);
    // math.round ties.
    assert_eq!(round(2.5, RoundTie::Away), 3.0);
    assert_eq!(round(-2.5, RoundTie::Away), -3.0);
    assert_eq!(round(2.5, RoundTie::Even), 2.0);
    assert_eq!(round(3.5, RoundTie::Even), 4.0);
    assert_eq!(round(-2.5, RoundTie::Up), -2.0);
    assert_eq!(round(2.5, RoundTie::Up), 3.0);
    assert_eq!(round(0.49999999999999994, RoundTie::Up), 0.0);
    // Modulo: *Operators*' worked example, modulo(-1, 100) = 99 floored.
    assert_eq!(mod_floored(-1, 100), Some(99));
    assert_eq!(mod_truncated(-1, 100), Some(-1));
    assert_eq!(mod_floored(7, -3), Some(-2));
    assert_eq!(mod_truncated(7, -3), Some(1));
    assert_eq!(mod_floored(5, 0), None);
    assert_eq!(mod_floored(i64::MIN, -1), Some(0));
    // pin:06-cond-call-state's two readings of a running sum inside `if cond`.
    let cond = [true, false, true, true];
    let run = |v: &[f64]| {
        let mut s = 0.0;
        v.iter()
            .map(|&a| {
                s += a;
                s
            })
            .collect::<Vec<f64>>()
    };
    same(&executed_only(&x, &cond, run), &[1.0, NA, 4.0, 8.0]);
    same(&every_bar(&x, &cond, run), &[1.0, NA, 6.0, 10.0]);
}

