#[test]
fn group_f_table_is_98_and_unique() {
    use pine_conformance::gen::group_f;
    let cells = group_f::cells();
    // r29 (2026-10-17): F099–F119 appended (`group_f2`, the next capture session's fixtures);
    // r34 (2026-10-18, R-P26): F120–F128 (`group_f3`, the probe sheet r34).
    assert_eq!(
        cells.len(),
        128,
        "F001–F098 (§4.2.6) + F099–F119 (r29) + F120–F128 (r34)"
    );
    let mut seen = std::collections::HashSet::new();
    for (i, c) in cells.iter().enumerate() {
        let id = c.script.id;
        assert_eq!(
            id,
            FixtureId::from_parts(Group::F, i as u16 + 1),
            "dense (I6)"
        );
        if let Some(t) = c.script.twin {
            let other = &cells[usize::from(t.number()) - 1];
            assert_eq!(other.script.twin, Some(id), "twins are mutual");
            assert_ne!(other.script.dialects, c.script.dialects);
        }
        // Unique: no two fixtures carry the same script modulo the id suffix and dialect.
        let norm = |t: &str| t.replace(id.as_str(), "ID");
        let key = (
            c.script.dialects.0,
            c.script.decl.as_deref().map(norm),
            c.script
                .body
                .iter()
                .map(|l| (l.depth, norm(&l.text)))
                .collect::<Vec<_>>(),
            c.script
                .plots
                .iter()
                .map(|(e, k)| (norm(e), k.clone()))
                .collect::<Vec<_>>(),
        );
        assert!(
            seen.insert(key),
            "{} duplicates an earlier fixture",
            id.as_str()
        );
        // A pin fixture's readings are named, distinct, and discriminate (§4.9.4).
        for (a, ra) in c.readings.iter().enumerate() {
            for rb in &c.readings[a + 1..] {
                assert_ne!(ra.name, rb.name, "{}", id.as_str());
                assert_ne!(
                    ra.body,
                    rb.body,
                    "{} readings do not discriminate",
                    id.as_str()
                );
            }
        }
    }
    // The F-pin block's window and readings (§4.2.6): head 1 unless stated.
    for c in &cells[72..98] {
        let n = c.script.id.number();
        let head = match n {
            87..=89 => 16,
            90 | 96 | 97 => 64,
            _ => 1,
        };
        assert_eq!(
            c.window,
            pine_conformance::fixture::Window::Head(head),
            "F{n:03}"
        );
        let named = matches!(n, 84 | 90 | 96 | 97);
        assert_eq!(c.readings.is_empty(), named, "F{n:03} readings");
    }
    // F031 carries U14's two readings; F084 is authored refuse 3008.
    let names: Vec<&str> = cells[30].readings.iter().map(|r| r.name.as_str()).collect();
    assert_eq!(names, ["selected_only", "both"]);
    assert_eq!(
        cells[83].expect,
        pine_conformance::fixture::Expect::Refuse {
            code: pine_ir::DiagCode(3008)
        }
    );
    // pin:06-w3-counter-plot: F030, F051, F052, F053 plot `cnt` beside the result.
    for n in [30usize, 51, 52, 53] {
        let p = &cells[n - 1].script.plots;
        assert_eq!(p.last().unwrap().1, "cnt", "F{n:03}");
    }
}

