fn group_a_is_the_full_cross_product() {
    use pine_conformance::fixture::{Expect, Oracle};
    use pine_conformance::gen::group_a;
    let cells = group_a::cells();
    assert_eq!(cells.len(), 96);
    for (i, c) in cells.iter().enumerate() {
        let id = c.script.id;
        assert_eq!(id.group(), Group::A);
        assert_eq!(usize::from(id.number()), i + 1, "dense A001..A096 (I6)");
        let (t, k) = (i / 16, i % 16 + 1);
        assert_eq!(
            c.script.about[1],
            format!("K{k:02} × {}", group_a::ROWS[t].name)
        );
        assert_eq!(c.script.dialects, group_a::ROWS[t].dialects);
        assert_eq!(
            matches!(c.expect, Expect::Refuse { .. }),
            c.oracle == Oracle::Authored
        );
        assert_eq!(c.tier, if k == 14 { 3 } else { 1 });
    }
    // The v6 bool row is §4.2.1's table, A081–A096; A090 is the only value cell.
    let want = [
        3007, 3007, 3005, 3005, 3007, 3007, 3005, 3005, 3007, 0, 3007, 3007, 3007, 3007, 3007, 3005,
    ];
    for (k, w) in want.iter().enumerate() {
        let c = &cells[80 + k];
        match c.expect {
            Expect::Refuse { code } => assert_eq!(code.0, *w, "A{:03}", 81 + k),
            Expect::Pending => assert_eq!(*w, 0, "A{:03}", 81 + k),
            _ => panic!("unexpected body"),
        }
        assert_eq!(
            c.script.twin,
            Some(FixtureId::from_parts(Group::A, 65 + k as u16))
        );
    }
    // The table's 3005 cells agree with pine_spec: the bool overload exists in v5 only.
    for (b, p) in [("nz", "source"), ("na", "x"), ("fixnan", "source")] {
        assert_eq!(
            group_a::builtin_refusal(b, p, pine_ir::Ty::Bool, pine_ir::Dialect::V6),
            Some(pine_ir::DiagCode(3005))
        );
        assert_eq!(
            group_a::builtin_refusal(b, p, pine_ir::Ty::Bool, pine_ir::Dialect::V5),
            None
        );
    }
    // Data refusals elsewhere: string has no nz / fixnan overload in either dialect (3010).
    let refused: Vec<String> = cells[..80]
        .iter()
        .filter_map(|c| match c.expect {
            Expect::Refuse { code } => Some(format!("{}:{}", c.script.id.as_str(), code.0)),
            _ => None,
        })
        .collect();
    assert_eq!(refused, ["A051:3010", "A052:3010", "A064:3010"]);
}

