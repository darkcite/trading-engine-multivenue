#[test]
fn group_b_wide_is_derived_from_spec() {
    use pine_conformance::fixture::{Align, Driver};
    use pine_conformance::gen::group_b::{self, FIXED_NAMES, IMPLICIT_BAR_READERS};
    let cells = group_b::cells();
    let (w, c) = group_b::derived_counts();
    assert_eq!(cells.len(), 76 + w + c, "76 fixed + B-wide + B-chart");
    for (i, cell) in cells.iter().enumerate() {
        assert_eq!(
            cell.script.id,
            FixtureId::from_parts(Group::B, i as u16 + 1),
            "dense (I6)"
        );
        // Data-derived ids carry no pin line (I15); B001–B076 carry pin:04-ta-reference.
        assert_eq!(
            cell.pins.iter().any(|p| p == "pin:04-ta-reference"),
            i < 76,
            "{}",
            cell.script.id.as_str()
        );
        assert_eq!(cell.pins.is_empty(), i >= 76);
    }
    // Authored readings (B007, B061, B064–B069, B076) are named, distinct and discriminate.
    for cell in &cells {
        for (a, ra) in cell.readings.iter().enumerate() {
            for rb in &cell.readings[a + 1..] {
                assert_ne!(ra.name, rb.name);
                assert_ne!(
                    ra.body,
                    rb.body,
                    "{} does not discriminate",
                    cell.script.id.as_str()
                );
            }
        }
    }
    let with: Vec<u16> = cells
        .iter()
        .filter(|c| !c.readings.is_empty())
        .map(|c| c.script.id.number())
        .collect();
    assert_eq!(with, [7, 61, 64, 65, 66, 67, 68, 69, 76]);
    // B-core: B004 is W5, B007 is U01, the conditional edge is cond-call-state.
    let has = |n: usize, p: &str| cells[n - 1].pins.iter().any(|x| x == p);
    assert!(has(4, "pin:W5-sma-na") && !has(4, "pin:U18-ta-na-propagation"));
    assert!(has(7, "pin:U01-ema-seed"));
    for f in 0..10 {
        assert!(has(6 * f + 5, "pin:06-cond-call-state"));
        if f > 0 {
            assert!(has(6 * f + 4, "pin:U18-ta-na-propagation"));
        }
    }
    // B-wide: re-derive from pine_spec independently of the generator's order.
    let wide = group_b::wide();
    assert_eq!(wide.len(), w);
    let mut names: Vec<&str> = wide.iter().map(|x| x.name).collect();
    let sorted = {
        let mut s = names.clone();
        s.sort();
        s
    };
    assert_eq!(names, sorted, "sorted by name");
    names.dedup();
    assert_eq!(names.len(), w, "one fixture per name");
    for e in pine_spec::ENTRIES.iter() {
        let n = e.full_str();
        if e.tier != pine_spec::Tier::T1 || e.ns.as_str() != "ta" {
            continue;
        }
        let excluded = FIXED_NAMES.contains(&n) || IMPLICIT_BAR_READERS.iter().any(|r| r.0 == n);
        if excluded {
            assert!(!names.contains(&n), "{n} is fixed or implicit");
        }
    }
    for x in ["ta.cci", "ta.cum", "ta.valuewhen", "ta.rci"] {
        assert!(names.contains(&x), "{x}");
    }
    // pin:06-b-wide-literal-number: a non-series float takes the literal 2.0.
    for x in [
        "ta.bb",
        "ta.bbw",
        "ta.percentile_linear_interpolation",
        "ta.percentile_nearest_rank",
    ] {
        assert!(names.contains(&x), "{x}");
    }
    // B-chart: Chart, align time, tail 256, after B-wide.
    for cell in &cells[76 + w..] {
        assert_eq!(cell.run.driver, Driver::Chart);
        assert_eq!(cell.run.align, Align::Time);
        assert_eq!(cell.window, pine_conformance::fixture::Window::Tail(256));
    }
}

