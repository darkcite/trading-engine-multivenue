//! Hyperliquid L1 execution — signing (E2) and the exchange arm (E3).
//!
//! E2 built everything needed to produce a byte-exact, correctly
//! signed exchange action and nothing that could send one. **E3 adds
//! the thing that sends it**: a mio + rustls HTTP/1.1 client
//! ([`http`]), the JSON request bodies ([`request`]), a fail-closed
//! answer scanner ([`response`]), the host/source interlock
//! ([`config`]) and the testnet gate ([`smoke`]).
//!
//! What has NOT changed is that nothing in this crate is reachable
//! from the engine yet: `cli::exec_boot::LIVE_ARM_VENUES` is still
//! empty, and a compile-time assertion holds it empty. The exchange
//! arm exists, is tested against a real TLS server, and is wired to
//! exactly one caller — the smoke, which cannot reach mainnet.
//!
//! ## The one hard problem
//!
//! **LAW E-3 — msgpack key order is part of the signature.** The
//! action is hashed as MessagePack, and MessagePack preserves the
//! order keys were written in. A different order is a different hash
//! is a rejected order — and the rejection carries no hint, because
//! the signature itself is valid, just over a digest the venue did not
//! compute.
//!
//! This cannot be settled by reading documentation, so it is settled
//! against the venue's own signer: `tests/fixtures/hl/vectors.tsv`
//! holds 25 known-answer vectors generated by the official
//! `hyperliquid-python-sdk`, and `tests/hl_vectors.rs` asserts this
//! crate reproduces every one of them **byte for byte** — the msgpack,
//! the connection id, the EIP-712 digest and the 65-byte signature.
//!
//! ## Doctrine
//!
//! Zero allocation on the encode/sign path: every action is built into
//! the arm's boot-owned msgpack buffer, the request body is rendered IN
//! PLACE (envelope head, action JSON, signature tail — one buffer, one
//! write per byte, no staging copy), prices and sizes render through a
//! stack `[u8; 24]`, and there is no `String`, no `Vec`, no `format!`
//! and no map anywhere on that path. POD structs are `#[repr(C)]` +
//! `Copy`. (`wire::WireNum`'s `Debug` impl uses `write!` — cold.)
//!
//! Fail-fast: an encode overflow is an error, never a truncation. A
//! half-written action that reached the signer would be a valid
//! signature over the wrong bytes, which is strictly worse than no
//! order at all.
//!
//! ## The second hard problem: an answer that lies about itself
//!
//! Hyperliquid returns **HTTP 200 for rejections**, and buries
//! per-order errors *inside* a `status:"ok"` envelope. Two traps, one
//! shape. [`response::scan`] is therefore fail-closed: every shape it
//! does not positively recognise as an acceptance is a refusal, and
//! [`response::tests`] fuzzes it against arbitrary bytes to prove it
//! never panics and never invents an acceptance.
//!
//! ## Where the arm is driven from
//!
//! On the `--exec` path the engine loop itself drives
//! `OrderDispatch::on_idle` (E6 commit 3a, `cli::paper::IdlePacer`):
//! every idle moment pumps the user-event socket, runs the LAW E-8
//! sweep, the reconciler and the budget persist — on the ENGINE thread,
//! with every step bounded (see `exchange`'s constants). E7 wires a
//! real [`exchange::HlExchange`] behind the router and hands it fill
//! lane 3's producer; the roll handler ([`exchange`]'s
//! `on_venue_event`) binds legs from real `outcomeCreated` events.
//!
//! ## What is deliberately NOT here
//!
//! * The **tape write** for a foreign fill (§6.1): a `userFills` row
//!   whose cloid is not ours is counted (`fills_foreign`) and never
//!   admitted to the lane, but it is not written to the capture.
//!   Recorded as open in `docs/risk-policy.md`.
//! * **Settlement booking.** The venue delivers settlement down
//!   `userFills` (`dir: "Settlement"`, px 1.0 or 0.0) with NO cloid,
//!   so it takes the foreign arm: counted, never booked. The operator
//!   ruled it should book; doing so needs a way to attribute a
//!   venue-originated fill to a slot without tripping LAW E-9's
//!   `STRATEGY_ID_NONE` fan-out. Recorded in `docs/risk-policy.md`.
//!
//! ## What E4 added, and what still cannot reach the engine
//!
//! [`cloid`] (LAW E-9), [`budget`], [`userws`], [`userws_conn`],
//! [`recon`] and [`exchange`] are built and tested. **The live arm is
//! now COMPILED INTO the binary** — what keeps it unreachable is that
//! nothing constructs it, plus `cli::exec_boot::LIVE_ARM_VENUES`
//! still being empty behind its compile-time assertion. That is a real
//! reduction in defence depth versus "no arm exists at all", and it is
//! recorded rather than glossed.

